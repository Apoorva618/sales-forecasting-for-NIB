"""## Fiscal Year Adjustment"""

# Month to number mapping for easier computation
month_to_num = {
    'Jan': 1, 'Feb': 2, 'Mar': 3, 'Apr': 4, 'May': 5, 'Jun': 6,
    'Jul': 7, 'Aug': 8, 'Sep': 9, 'Oct': 10, 'Nov': 11, 'Dec': 12
}
num_to_month = {v: k for k, v in month_to_num.items()}

# Function to calculate fiscal month, fiscal year, and fiscal date
def calculate_fiscal_date(row):
    month_num = month_to_num[row['calendar_month']]
    fiscal_month_num = (month_num + 3 - 1) % 12 + 1  # Shift by 3 months
    fiscal_year = row['calendar_year'] + (1 if fiscal_month_num <= 3 else 0)  # Adjust year if fiscal month is Jan-Mar
    fiscal_month = num_to_month[fiscal_month_num]
    fiscal_date = pd.Timestamp(year=fiscal_year, month=fiscal_month_num, day=1)  # Create first day of fiscal month
    return pd.Series([fiscal_month, fiscal_year, fiscal_date])

