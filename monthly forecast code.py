    # Step 2: Create sequences
    def create_sequences(data, n_steps):
        X, y = [], []
        for j in range(len(data) - n_steps):
            X.append(data[j:j + n_steps])
            y.append(data[j + n_steps])
        return np.array(X), np.array(y)

    n_steps = 12  # Use 12 months for forecasting
    X, y = create_sequences(scaled_data, n_steps)

    # Reshape the data to fit the model input requirements
    X = X.reshape((X.shape[0], X.shape[1], 1))

    # Step 3: Define the CNN model
    model = Sequential([
        Conv1D(filters=32, kernel_size=3, activation='relu', input_shape=(n_steps, 1)),
        MaxPooling1D(pool_size=2),
        Flatten(),
        Dense(16, activation='relu'),
        Dense(1)
    ])
    model.compile(optimizer='adam', loss='mean_squared_error')

    # Step 4: Train the model using all available data
    model.fit(X, y, epochs=50, batch_size=16, verbose=1)

    # Step 5: Forecast for the next 24 months
    future_steps = 24
    future_predictions = []

    # Use the last n_steps from the scaled data as the starting point
    last_sequence = scaled_data[-n_steps:].reshape(1, n_steps, 1)

    for _ in range(future_steps):
        # Predict the next value
        next_value = model.predict(last_sequence).flatten()[0]
        future_predictions.append(next_value)

        # Update the sequence with the predicted value
        last_sequence = np.append(last_sequence[:, 1:, :], [[[next_value]]], axis=1)

    # Inverse transform the future predictions to the original scale
    future_predictions = scaler.inverse_transform(np.array(future_predictions).reshape(-1, 1)).flatten()

    # Generate future dates starting from the last date in the dataset
    last_date = de_covid_df.index[-1]
    future_dates = pd.date_range(start=last_date, periods=future_steps + 1, freq='M')[1:]

