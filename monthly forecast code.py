for i in sales_columns:
  # Use only "Train" type data for modeling
  train_data = de_covid_df[i]

  # Scale the data
  scaler = MinMaxScaler(feature_range=(0, 1))
  scaled_data = scaler.fit_transform(train_data.values.reshape(-1, 1))

  # Step 2: Create sequences
  def create_sequences(data, n_steps):
      X, y = [], []
      for i in range(len(data) - n_steps):
          X.append(data[i:i + n_steps])
          y.append(data[i + n_steps])
      return np.array(X), np.array(y)

  n_steps = 12  # Use 12 months for forecasting
  X, y = create_sequences(scaled_data, n_steps)

  # Step 3: Train-test split (80% train, 20% test)
  train_size = int(0.8 * len(X))
  X_train, X_test = X[:train_size], X[train_size:]
  y_train, y_test = y[:train_size], y[train_size:]

  # Reshape the data to fit the model input requirements
  X_train = X_train.reshape((X_train.shape[0], X_train.shape[1], 1))
  X_test = X_test.reshape((X_test.shape[0], X_test.shape[1], 1))

  # Step 4: Define the CNN model
  model = Sequential([
      Conv1D(filters=32, kernel_size=3, activation='relu', input_shape=(n_steps, 1)),
      MaxPooling1D(pool_size=2),
      Flatten(),
      Dense(16, activation='relu'),
      Dense(1)
  ])

  model.compile(optimizer='adam', loss='mean_squared_error')

  # Step 5: Train the model
  history = model.fit(X_train, y_train, epochs=50, batch_size=16, verbose=1)

  # Step 6: Forecast for the test period
  y_pred = model.predict(X_test).flatten()

  # Inverse transform the predictions and actuals
  y_pred = scaler.inverse_transform(y_pred.reshape(-1, 1)).flatten()
  y_test = scaler.inverse_transform(y_test.reshape(-1, 1)).flatten()

  # Step 7: Calculate evaluation metrics
  mae = mean_absolute_error(y_test, y_pred)
  rmse = np.sqrt(mean_squared_error(y_test, y_pred))
  mape = np.mean(np.abs((y_test - y_pred) / y_test)) * 100
  r2 = r2_score(y_test, y_pred)

  # Print evaluation metrics
  print(f"MAE: {mae}")
  print(f"RMSE: {rmse}")
  print(f"MAPE: {mape}%")
  print(f"R²: {r2}")

  # Step 8: Plot actual vs forecasted values
  plt.figure(figsize=(12, 6))

  # Plot the training data
  train_index = train_data.index[:train_size + n_steps]
  test_index = train_data.index[train_size + n_steps:]

  plt.plot(train_index, scaler.inverse_transform(scaled_data[:train_size + n_steps]), label='Train Data', color='blue')

  # Plot the test data and predictions
  plt.plot(test_index, y_test, label='Test Data', color='green')
  plt.plot(test_index, y_pred, label='Forecasted Sales (CNN)', color='red', linestyle='--')

